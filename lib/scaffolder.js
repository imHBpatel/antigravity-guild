/**
 * Scaffold a hermetic test suite for an existing file.
 */
function scaffoldTest(projectRoot, targetFilePath, options = {}) {
  const fullPath = path.isAbsolute(targetFilePath) ? targetFilePath : path.join(projectRoot, targetFilePath);
  const baseName = path.basename(fullPath, path.extname(fullPath));
  const dirs = resolveProjectDirs(projectRoot);
  const testFile = path.join(dirs.testDir, `${baseName}.scaffold.test.js`);

  const relTarget = path.relative(path.dirname(testFile), fullPath).replace(/\\/g, '/');
  const requirePath = relTarget.startsWith('.') ? relTarget : `./${relTarget}`;

  let exportedSymbols = [];
  if (fs.existsSync(fullPath)) {
    try {
      const content = fs.readFileSync(fullPath, 'utf8');
      const moduleExportMatch = content.match(/module\.exports\s*=\s*{([^}]+)}/);
      if (moduleExportMatch) {
        exportedSymbols = moduleExportMatch[1]
          .split(',')
          .map(s => s.trim().split(':')[0].trim())
          .filter(s => s && !s.startsWith('_') && !s.startsWith('//'));
      }
    } catch (_) {}
  }

  const symbolList = exportedSymbols.length > 0 ? exportedSymbols.join(', ') : 'targetModule';
  const symbolChecks = exportedSymbols.length > 0
    ? exportedSymbols.map(s => `  assert(target.${s} !== undefined, 'Export "${s}" should be defined');`).join('\n')
    : `  assert(typeof target === 'object' || typeof target === 'function', 'Module should export a valid definition');`;

  const testContent = `'use strict';

/**
 * Hermetic Test Suite for ${baseName}
 * Generated by OmniGuild Council Scaffolder.
 */
const assert = require('assert');
const target = require('${requirePath}');

console.log('🧪 Running ${baseName} Scaffold Invariant Tests...');

// 1. Module Export Integrity
{
${symbolChecks}
  console.log('  ✔ Module export integrity verified');
}

// 2. Deterministic Baseline Invocation
{
  assert(target !== null && target !== undefined, 'Exported module should not be null');
  console.log('  ✔ Non-null baseline verified');
}

console.log('✨ All ${baseName} Tests Passed Deterministically!\\n');
`;

  const filesWritten = [];
  if (!options.dryRun) {
    if (!fs.existsSync(dirs.testDir)) {
      fs.mkdirSync(dirs.testDir, { recursive: true });
    }
    fs.writeFileSync(testFile, testContent, 'utf8');
    filesWritten.push(testFile);
  }

  return {
    type: 'test',
    targetFile: fullPath,
    testFile,
    files: [testFile],
    filesWritten,
    summary: `Scaffolded hermetic test suite for ${baseName}.`,
  };
}

/**
 * Dispatcher for omniguild scaffold command.
 */
function runScaffold(projectRoot, type, name, options = {}) {
  const normType = (type || '').toLowerCase();

  switch (normType) {
    case 'api':
    case 'rest':
    case 'endpoint':
      return scaffoldApi(projectRoot, name, options);

    case 'ui':
    case 'component':
    case 'view':
      return scaffoldUi(projectRoot, name, options);

    case 'test':
    case 'tests':
    case 'spec':
      return scaffoldTest(projectRoot, name, options);

    default:
      throw new Error(`Unknown scaffold type: "${type}". Supported types: api, ui, test.`);
  }
}

